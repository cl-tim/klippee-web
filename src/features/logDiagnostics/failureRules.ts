export function matchingFailureRules(message: string): FailureRule[] {
  const matches = failureRules.filter((rule) => rule.patterns.some((pattern) => pattern.test(message)));
  // Klipper uses the homing machinery for probing as well as axis homing.
  return matches.some((rule) => rule.id === "probe-no-trigger")
    ? matches.filter((rule) => rule.id !== "homing-failure")
    : matches;
}
