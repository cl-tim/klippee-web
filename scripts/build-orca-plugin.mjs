import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
// Normalize before embedding HTML so Windows and CI produce identical files.
const read = async (name) => (await readFile(new URL(`plugins/orcaslicer/${name}`, root), "utf8")).replace(/\r\n/g, "\n");
const [core, restore, plugin, page] = await Promise.all([read("capture_core.py"), read("restore_core.py"), read("klippee_plugin.py"), read("klippee_plugin.html")]);
const header = `# /// script
# requires-python = ">=3.12"
# [tool.orcaslicer.plugin]
# id = "klippee"
# name = "Klippee"
# description = "Import your profile library and save or restore complete slicer setups."
# author = "Klippee"
# version = "1.6.0"
# ///
# Generated by scripts/build-orca-plugin.mjs; edit plugins/orcaslicer sources.
`;
const result = header + `\n_KLIPPEE_PAGE = ${JSON.stringify(page)}\n\n` + core + "\n\n" + restore.replace(/^from capture_core import .*\r?\n/m, "") + "\n\n" + plugin.replace(/^from (capture_core|restore_core) import .*\r?\n/gm, "");
await writeFile(new URL("public/install/klippee_orca.py", root), result, "utf8");
console.log(`Built ${fileURLToPath(new URL("public/install/klippee_orca.py", root))}`);
